export function searchCities(query: string): CityData[] {
  if (!query.trim()) return [];
  const q = query.trim().toLowerCase();
  return CITIES.filter(
    (c) => c.name.toLowerCase().includes(q) || c.region.toLowerCase().includes(q)
  );
}

